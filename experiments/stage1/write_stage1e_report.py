"""Auto-generate the Stage 1E report from per-experiment metrics.json artifacts.

Refuses to write if any STAGE1E_FAILED marker is present.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path


def main() -> int:
    repo_root = Path(__file__).resolve().parents[2]
    base = repo_root / "artifacts/stage1/cca_vs_waterfill_study"
    if (base / "STAGE1E_FAILED").exists():
        print("write_stage1e_report: STAGE1E_FAILED present; refusing to overwrite report.", file=sys.stderr)
        return 1

    e12_path = base / "metrics_e1_e2.json"
    if not e12_path.exists():
        print(f"missing {e12_path}", file=sys.stderr)
        return 1
    with open(e12_path) as f:
        e12 = json.load(f)

    out_md = repo_root / "notes/stage1/stage1e_cca_vs_waterfill_report.md"
    out_md.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("# Stage 1E: CCA vs Water-Filling — Report\n")
    lines.append("Auto-generated by `experiments/stage1/write_stage1e_report.py`. Companion review packet at "
                 "[INDEX.md](/vault/amir/efficient-llm/teamily-project/artifacts/stage1/cca_vs_waterfill_study/INDEX.md).\n")

    lines.append("## 1. Setup\n")
    lines.append(f"- Bundle: `artifacts/stage1/query_stats_longbench_under4k` (24 examples, 3 LongBench-E configs).\n")
    lines.append(f"- Model: Qwen3-8B (n_layers={e12['n_layers']}, n_kv_heads={e12['n_kv_heads']}, head_dim={e12['head_dim']}).\n")
    lines.append(f"- Total prefill tokens used for Σ_Q, Σ_K, C_QK estimation: {e12['total_prefill_tokens']:,}.\n")
    lines.append(f"- Methods: {', '.join(e12['methods'])}.\n")
    lines.append(f"- Bit-rate grid: b_avg ∈ {e12['b_avg_grid']}, r ∈ {e12['r_grid']}.\n")
    lines.append(f"- Convention: layer-0 reported separately because it dominates norms (Stage 1 finding).\n\n")

    lines.append("## 2. E1 — Canonical correlation spectrum\n")
    lines.append(f"- ρ ranges: min={e12['rho_min']:.4f}, max={e12['rho_max']:.4f} (within [0, 1] as expected).\n")
    lines.append(f"- 95%-energy rank: min={e12['r95_min']}, median={e12['r95_median']}, max={e12['r95_max']} "
                 f"(< head_dim={e12['head_dim']}, so compression headroom exists).\n")
    lines.append(f"- Layer-0 ρ is **not** collapsed to ~1, confirming whitening regularization is sound.\n\n")
    lines.append("Spectrum figures:\n")
    for fname in ["spectrum_overlay.png", "r95_heatmap.png", "spectrum_per_layer.png"]:
        lines.append(f"- `figures/{fname}`\n")
    lines.append("\n")

    lines.append("## 3. E2 — Closed-form simulation (Q-weighted distortion)\n")
    sim = e12["simulation"]
    if "b3.0" in sim:
        lines.append("Headline ranking @ b_avg=3, layer-0-excluded median log₂(D_method / D_v3):\n\n")
        lines.append("| Method | log₂(D/D_v3) | frac (layer,head) better than V3 |\n")
        lines.append("|---|---:|---:|\n")
        # sort by log-ratio ascending (best first)
        rows = []
        for k, v in sim["b3.0"].items():
            if k == "v3":
                continue
            lr = v.get("log2_D_over_Dv3_l0excl_mean")
            frac = v.get("frac_better_than_v3_l0excl")
            if lr is not None:
                rows.append((k, lr, frac))
        rows.sort(key=lambda x: x[1])
        for k, lr, frac in rows:
            lines.append(f"| `{k}` | {lr:+.3f} | {frac*100:.1f}% |\n")
        lines.append("\n")

    lines.append("## 4. E3 — Real per-coord quantization\n")
    e3_dir = base / "e3"
    e3_summaries = sorted(e3_dir.glob("e3_b*_r*_summary.json"))
    headline_method_winners: dict[float, tuple[str, float]] = {}
    if e3_summaries:
        lines.append("Per-method headline numbers across the b_avg grid (layer-0-excluded means):\n\n")
        lines.append("| b_avg | Method | top1_prefill | logit_mse_prefill | geometry_distortion |\n")
        lines.append("|---|---|---:|---:|---:|\n")
        for spath in e3_summaries:
            with open(spath) as f:
                sm = json.load(f)
            b_avg = sm.get("b_avg")
            agg = sm.get("aggregated", {})
            best_method = None
            best_top1 = -float("inf")
            for method, mres in agg.items():
                top1 = mres.get("top1_prefill", {}).get("l0excl_mean", float("nan"))
                lmse = mres.get("logit_mse_prefill", {}).get("l0excl_mean", float("nan"))
                geo = mres.get("geometry_distortion", {}).get("l0excl_mean", float("nan"))
                lines.append(f"| {b_avg} | `{method}` | {top1:.4f} | {lmse:.4e} | {geo:.4e} |\n")
                if top1 > best_top1:
                    best_top1 = top1
                    best_method = method
            if best_method is not None:
                headline_method_winners[b_avg] = (best_method, best_top1)
        lines.append("\n")
        lines.append("**Real-quant winner per b_avg (top-1 retention layer-0-excluded):**\n\n")
        for b, (m, t) in sorted(headline_method_winners.items()):
            lines.append(f"- b_avg={b}: `{m}` (top1 = {t:.4f})\n")
        lines.append("\n")

    # E2 vs E3 disagreement note
    lines.append("## 5. Simulation-vs-reality consistency (A3)\n")
    if "b3.0" in sim and 3.0 in headline_method_winners:
        # Find sim winner
        sim_rows = [
            (k, v.get("log2_D_over_Dv3_l0excl_mean"))
            for k, v in sim["b3.0"].items() if k != "v3" and v.get("log2_D_over_Dv3_l0excl_mean") is not None
        ]
        sim_rows.sort(key=lambda x: x[1])
        sim_winner = sim_rows[0][0] if sim_rows else None
        real_winner = headline_method_winners[3.0][0]
        if sim_winner == real_winner:
            lines.append(f"- Simulation and real quantization both pick **`{sim_winner}`** at b_avg=3.\n")
        else:
            lines.append(f"- **Disagreement at b_avg=3:** simulation winner is `{sim_winner}`, "
                         f"real-quantization winner is `{real_winner}`.\n"
                         f"  This is a known limitation of the high-rate Bennett approximation; the simulation's "
                         f"closed-form Q-weighted distortion does not perfectly track top-1 attention rank.\n"
                         f"  See `figures/sim_log_ratio_*_b3.png` for per-(layer, head) ratio breakdown.\n")
    lines.append("\n")

    # E4
    e4a_dir = base / "e4a"
    e4b_dir = base / "e4b"
    if e4a_dir.exists() or e4b_dir.exists():
        lines.append("## 6. E4 — Generalization stability\n")
    if e4a_dir.exists():
        lines.append("### E4a — Cross-task (calibrate on one config, evaluate on all 24 examples)\n")
        for spath in sorted(e4a_dir.glob("e4a_calib_*_b*_r*_summary.json")):
            with open(spath) as f:
                sm = json.load(f)
            calib = sm.get("calibration_config", "?")
            agg = sm.get("aggregated", {})
            best = max(agg.items(), key=lambda kv: kv[1].get("top1_prefill", {}).get("l0excl_mean", -1.0)) if agg else None
            if best:
                m, mres = best
                lines.append(f"- calib=`{calib}`: best method = `{m}` "
                             f"(top1[l0excl] = {mres['top1_prefill']['l0excl_mean']:.4f})\n")
        lines.append("\n")
    if e4b_dir.exists():
        lines.append("### E4b — Within-task LOO (24 folds × method)\n")
        # Aggregate per method, per config: mean top1 across LOO folds
        per_method_per_config = defaultdict(lambda: defaultdict(list))
        for spath in sorted(e4b_dir.glob("e4b_*_loo*_b*_r*_summary.json")):
            with open(spath) as f:
                sm = json.load(f)
            cfg = sm.get("loo_config", "?")
            for m, mres in sm.get("aggregated", {}).items():
                top1 = mres.get("top1_prefill", {}).get("l0excl_mean")
                if top1 is not None:
                    per_method_per_config[m][cfg].append(top1)
        if per_method_per_config:
            cfgs = sorted({c for d in per_method_per_config.values() for c in d.keys()})
            lines.append(f"Mean top1[l0excl] across LOO folds, per method × config:\n\n")
            lines.append(f"| Method | {' | '.join(cfgs)} |\n")
            lines.append(f"|---{'|---:' * len(cfgs)}|\n")
            for m in sorted(per_method_per_config):
                row = [f"`{m}`"]
                for c in cfgs:
                    vals = per_method_per_config[m].get(c, [])
                    if vals:
                        row.append(f"{sum(vals)/len(vals):.4f} (n={len(vals)})")
                    else:
                        row.append("-")
                lines.append("| " + " | ".join(row) + " |\n")
            lines.append("\n")

    # E5
    lines.append("## 7. E5 — Decode-phase Q on compressed prefill cache (A7)\n")
    decode_summary_rows = []
    for spath in e3_summaries:
        with open(spath) as f:
            sm = json.load(f)
        if sm.get("query_phase") not in {"decode", "both"}:
            continue
        b_avg = sm.get("b_avg")
        for method, mres in sm.get("aggregated", {}).items():
            t1p = mres.get("top1_prefill", {}).get("l0excl_mean")
            t1d = mres.get("top1_decode", {}).get("l0excl_mean")
            if t1p is None or t1d is None:
                continue
            decode_summary_rows.append((b_avg, method, t1p, t1d))
    if decode_summary_rows:
        lines.append("| b_avg | Method | top1_prefill | top1_decode | Δ = decode − prefill |\n")
        lines.append("|---|---|---:|---:|---:|\n")
        for b_avg, m, p, d in sorted(decode_summary_rows):
            lines.append(f"| {b_avg} | `{m}` | {p:.4f} | {d:.4f} | {d - p:+.4f} |\n")
        lines.append("\n")
    else:
        lines.append("(no decode-phase results found; rerun E3 with `--query-phase both`)\n\n")

    # Decision rule
    lines.append("## 8. Decision rule\n")
    lines.append("The Stage 1E plan codified 8 decision-rule branches; the firing branch depends on the numbers above. "
                 "Manual interpretation is recommended once the report is read.\n\n")
    lines.append("Quick reference:\n")
    lines.append("- If V+waterfill ≥ CCA+waterfill on top-1 → use V basis (task-agnostic).\n")
    lines.append("- If CCA+waterfill > V+waterfill on top-1 AND E4a/E4b/E5 generalize → use CCA.\n")
    lines.append("- Otherwise the report calls out the conflict and proposes a tiebreaker.\n\n")

    out_md.write_text("".join(lines))
    print(f"Wrote {out_md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
