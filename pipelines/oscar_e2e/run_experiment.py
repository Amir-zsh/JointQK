#!/usr/bin/env python3
"""Declarative experiment runner for the OSCAR-vq served evals.

One JSON spec (pipelines/oscar_e2e/experiments/*.json) states everything a
replication needs: model, per-method serve args + env + calibration
artifacts, cells with rows/shards/sampling. This script materializes it:

  <out_root>/experiment_manifest.json   resolved spec + git SHAs (repo AND
                                        engine clone) + sha256 of every
                                        calibration artifact + row counts
  <out_root>/arms/<method>.sh           sourceable per-method serve config
                                        (the pool runner's spec mode)
  <queue.tsv>                           sharded job queue for gpu_pool_runner

Run (from repo root):
  .venv/bin/python pipelines/oscar_e2e/run_experiment.py \
      --spec pipelines/oscar_e2e/experiments/llama31_8b_grid_v2.json \
      --queue logs/pool_queue_llama_v2.tsv
  for g in 1 2 3 4 5 6; do
      ARMS_DIR=<out_root>/arms nohup bash pipelines/oscar_e2e/gpu_pool_runner.sh \
          logs/pool_queue_llama_v2.tsv $g & done
  .venv/bin/python pipelines/oscar_e2e/merge_shards.py --root <out_root>
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def sha256_file(p: Path, cap_mb: int = 2048) -> str:
    if not p.exists() or not p.is_file():
        return "MISSING"
    h = hashlib.sha256()
    with p.open("rb") as fh:
        while chunk := fh.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def git_sha(path: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(path), "rev-parse", "HEAD"], text=True).strip()
    except subprocess.CalledProcessError:
        return "UNKNOWN"


def shard_rows(rows_path: Path, n: int) -> list[Path]:
    lines = rows_path.read_text().splitlines()
    outs = []
    base = rows_path.with_suffix("")
    for i in range(n):
        p = Path(f"{base}__s{i}of{n}.jsonl")
        if not p.exists():
            p.write_text("\n".join(lines[i::n]) + "\n")
        outs.append(p)
    return outs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--queue", required=True)
    ap.add_argument("--methods", nargs="*", default=None,
                    help="subset of spec methods (default: all)")
    args = ap.parse_args()

    spec = json.loads((REPO / args.spec).read_text())
    out_root = REPO / spec["out_root"]
    arms_dir = out_root / "arms"
    arms_dir.mkdir(parents=True, exist_ok=True)

    methods = spec["methods"]
    if args.methods:
        missing = set(args.methods) - set(methods)
        assert not missing, f"unknown methods: {missing}"
        methods = {k: methods[k] for k in args.methods}

    # Per-method sourceable serve config — the arguments ARE the record.
    for name, m in methods.items():
        lines = [
            "#!/bin/bash",
            f"# generated by run_experiment.py from {args.spec} — do not hand-edit",
            f'MODEL="{spec["model"]}"',
        ]
        for k, v in m.get("env", {}).items():
            val = v if Path(v).is_absolute() or "/" not in v else f"$ROOT/{v}"
            lines.append(f'export {k}="{val}"')
        serve = " ".join(f'"{a}"' for a in m.get("serve_args", []))
        lines.append(f"SERVE_EXTRA=({serve})")
        (arms_dir / f"{name}.sh").write_text("\n".join(lines) + "\n")

    # Queue.
    jobs = []
    for cell in spec["cells"]:
        rows = REPO / cell["rows"]
        assert rows.exists(), f"rows missing: {cell['rows']}"
        for method in methods:
            cell_dir = f"{spec['out_root']}/{method}"
            if (REPO / cell_dir / cell["name"] / "metrics.json").exists():
                continue
            if cell["shards"] == 1:
                jobs.append((method, f"{cell_dir}/{cell['name']}",
                             cell["rows"], cell["client_args"]))
                continue
            for i, sp in enumerate(shard_rows(rows, cell["shards"])):
                out = f"{cell_dir}/{cell['name']}__s{i}"
                if (REPO / out / "metrics.json").exists():
                    continue
                jobs.append((method, out, str(sp.relative_to(REPO)),
                             cell["client_args"]))
    # method-major so arm-affinity claiming keeps servers alive
    jobs.sort(key=lambda j: j[0])
    qp = REPO / args.queue
    qp.parent.mkdir(parents=True, exist_ok=True)
    with qp.open("w") as fh:
        for m, od, rows, extra in jobs:
            fh.write(f"TODO\t{m}\t{od}\t{rows}\t{extra}\n")

    # Manifest.
    calib = spec.get("calibration", {})
    manifest = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "spec_file": args.spec,
        "spec": spec,
        "methods_run": sorted(methods),
        "git": {
            "repo": git_sha(REPO),
            "engine_clone": git_sha(REPO / spec.get("engine_clone", "vendor/OSCAR-vq")),
        },
        "artifact_sha256": {
            k: sha256_file(REPO / v)
            for k, v in calib.items()
            if isinstance(v, str) and (REPO / v).is_file()
        },
        "rotation_files_sha256": {
            f.name: sha256_file(f)
            for f in sorted((REPO / calib["rotations"]).glob("*.pt"))
        } if calib.get("rotations") and (REPO / calib["rotations"]).is_dir() else {},
        "cells": [
            {**c, "n_rows": sum(1 for _ in (REPO / c["rows"]).open())}
            for c in spec["cells"]
        ],
        "queue": {"file": args.queue, "n_jobs": len(jobs)},
    }
    (out_root / "experiment_manifest.json").write_text(
        json.dumps(manifest, indent=2))

    print(f"[exp] {spec['name']}: {len(jobs)} jobs -> {qp}")
    print(f"[exp] arms: {sorted(methods)} -> {arms_dir.relative_to(REPO)}")
    print(f"[exp] manifest -> {(out_root / 'experiment_manifest.json').relative_to(REPO)}")
    if not jobs:
        print("[exp] nothing to do (all cells complete)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
